// Regenerates packages/proposal-renderer/src/fonts/*.ts (base64 modules) from the TTFs in packages/proposal-renderer/fonts.
// Fonts are inlined so the PDF renderer works inside a Cloudflare Worker and under Vitest with no file or network access.
// Usage: node scripts/gen-fonts.mjs
import fs from "node:fs";
import path from "node:path";

const src = path.resolve("packages/proposal-renderer/fonts");
const out = path.resolve("packages/proposal-renderer/src/fonts");
fs.mkdirSync(out, { recursive: true });
for (const file of fs.readdirSync(src).filter((f) => f.endsWith(".ttf"))) {
  const name = file.replace(/\.ttf$/, "").replace(/([a-z])([A-Z])/g, "$1-$2").toLowerCase();
  const b64 = fs.readFileSync(path.join(src, file)).toString("base64");
  fs.writeFileSync(path.join(out, `${name}.ts`), `// Generated by scripts/gen-fonts.mjs from ${file} (SIL Open Font License 1.1, see ../../fonts/OFL.txt). Do not edit.\nexport default "${b64}";\n`);
  console.log(`${name}.ts  ${(b64.length / 1024).toFixed(0)} KB`);
}
